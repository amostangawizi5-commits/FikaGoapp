const express = require('express');
const router = express.Router();
const { authenticate, authorize } = require('../middlewares/auth');
const admin = require('../controllers/adminController');
router.use(authenticate, authorize('admin'));
router.get('/people', admin.getPeople);
router.put('/people/:role/:id', admin.updatePerson);
router.get('/people/:role/:id/details', admin.getPersonDetails);
router.get('/orders', admin.getOrders);
router.get('/orders/:id', admin.getOrderDetails);
router.put('/orders/:id/cancel', admin.cancelOrder);
router.post('/orders/:id/refund', admin.issueRefund);
router.get('/promotions', admin.getPromotions);
router.post('/promotions', admin.savePromotion);
router.put('/promotions/:id', admin.updatePromotion);
router.delete('/promotions/:id', admin.deletePromotion);
router.get('/complaints', admin.getComplaints);
router.put('/complaints/:id', admin.updateComplaint);
module.exports = router;
